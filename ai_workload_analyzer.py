# SECTION 8 : FILE HANDLING HELPERS
# =============================================================================
def load_job_from_file(path: str) -> ImageJob:
    if not os.path.exists(path):
        raise InvalidJobFileError(f"Input file not found: {path}")
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except json.JSONDecodeError as exc:
        raise InvalidJobFileError(f"Malformed JSON in {path}: {exc}") from exc
    return ImageJob.from_dict(data), data


def save_report(report: Dict, out_path: str) -> None:
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)


# =============================================================================
# SECTION 9 : DRIVER / MAIN
# =============================================================================
def main():
    input_path = os.path.join(os.path.dirname(__file__), "sample_workload.json")
    output_path = os.path.join(os.path.dirname(__file__), "performance_report.json")

    try:
        job, raw = load_job_from_file(input_path)

        # --- 1. Pipeline analysis --------------------------------------
        pipeline = PipelineSimulator(job.instructions, clock_period_ns=1.0)
        pipeline_result = pipeline.run()

        # --- 2. Cache analysis (addresses from LOAD/STORE only) --------
        addresses = [i.mem_address for i in job.instructions if i.is_memory_op() and i.mem_address is not None]
        cache_cfg = raw["cache_config"]
        cache = CacheAnalyzer(addresses, cache_cfg, main_mem_latency=raw.get("main_memory_latency_cycles", 100))
        cache_result = cache.run()

        # --- 3. I/O analysis ---------------------------------------------
        io_cfg = raw["io_config"]
        total_data_kb = job.num_images * job.image_size_kb
        io = IOAnalyzer(total_data_kb, io_cfg["transfer_rate_kbps"], io_cfg["num_requests"])
        io_result = io.run()

        # --- 4. Consolidated report ---------------------------------------
        generator = PerformanceReportGenerator(job, pipeline_result, cache_result, io_result)
        report = generator.build()
        generator.print_report(report)
        save_report(report, output_path)
        print(f"\nFull JSON report saved to: {output_path}")

        for analyzer_summary in (pipeline.summary(), cache.summary(), io.summary()):
            print("  >", analyzer_summary)

    except WorkloadAnalyzerError as exc:
        print(f"[ERROR] {type(exc).__name__}: {exc}")
    except Exception as exc:  # safety net for any unexpected error
        print(f"[UNEXPECTED ERROR] {exc}")


if __name__ == "__main__":
    main()
