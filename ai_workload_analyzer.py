# SECTION 6 : I/O TRANSFER ANALYZER (Interrupt-driven vs DMA)  -- polymorphism
# =============================================================================
class IOTransferStrategy(ABC):
    def __init__(self, total_data_kb: float, transfer_rate_kbps: float, num_requests: int):
        if transfer_rate_kbps <= 0 or num_requests <= 0:
            raise IOConfigurationError("Transfer rate and request count must be positive")
        self.total_data_kb = total_data_kb
        self.transfer_rate_kbps = transfer_rate_kbps
        self.num_requests = num_requests

    @abstractmethod
    def transfer_time_ms(self) -> float: ...

    @abstractmethod
    def cpu_interventions(self) -> int: ...

    @abstractmethod
    def cpu_utilization_percent(self) -> float: ...


class InterruptDrivenIO(IOTransferStrategy):
    OVERHEAD_MS_PER_INTERRUPT = 0.05   # context-switch / ISR overhead

    def transfer_time_ms(self) -> float:
        base = (self.total_data_kb / self.transfer_rate_kbps) * 1000
        return round(base + self.num_requests * self.OVERHEAD_MS_PER_INTERRUPT, 3)

    def cpu_interventions(self) -> int:
        return self.num_requests            # CPU interrupted for every request

    def cpu_utilization_percent(self) -> float:
        busy = self.num_requests * self.OVERHEAD_MS_PER_INTERRUPT
        return round(min(100.0, (busy / self.transfer_time_ms()) * 100), 2)


class DMAIO(IOTransferStrategy):
    SETUP_MS_PER_REQUEST = 0.01          # CPU only sets up / ends the DMA burst

    def transfer_time_ms(self) -> float:
        base = (self.total_data_kb / self.transfer_rate_kbps) * 1000
        return round(base + self.num_requests * self.SETUP_MS_PER_REQUEST * 0.2, 3)

    def cpu_interventions(self) -> int:
        return 2                             # one setup + one completion signal only

    def cpu_utilization_percent(self) -> float:
        busy = self.num_requests * self.SETUP_MS_PER_REQUEST
        return round(min(100.0, (busy / self.transfer_time_ms()) * 100), 2)


class IOAnalyzer(BaseAnalyzer):
    def __init__(self, total_data_kb: float, transfer_rate_kbps: float, num_requests: int):
        super().__init__("I/O & DMA Comparator")
        self.interrupt_io = InterruptDrivenIO(total_data_kb, transfer_rate_kbps, num_requests)
        self.dma_io = DMAIO(total_data_kb, transfer_rate_kbps, num_requests)
        self.result: Dict = {}

    def run(self) -> Dict:
        interrupt_stats = {
            "transfer_time_ms": self.interrupt_io.transfer_time_ms(),
            "cpu_interventions": self.interrupt_io.cpu_interventions(),
            "cpu_utilization_percent": self.interrupt_io.cpu_utilization_percent(),
        }
        dma_stats = {
            "transfer_time_ms": self.dma_io.transfer_time_ms(),
            "cpu_interventions": self.dma_io.cpu_interventions(),
            "cpu_utilization_percent": self.dma_io.cpu_utilization_percent(),
        }
        more_efficient = "DMA" if dma_stats["transfer_time_ms"] <= interrupt_stats["transfer_time_ms"] \
            and dma_stats["cpu_utilization_percent"] <= interrupt_stats["cpu_utilization_percent"] else "Interrupt-driven"

        self.result = {
            "interrupt_driven": interrupt_stats,
            "dma": dma_stats,
            "more_efficient_method": more_efficient,
        }
        return self.result

    def summary(self) -> str:
        r = self.result
        return (f"I/O: Interrupt={r['interrupt_driven']['transfer_time_ms']}ms "
                f"vs DMA={r['dma']['transfer_time_ms']}ms -> {r['more_efficient_method']} preferred")


