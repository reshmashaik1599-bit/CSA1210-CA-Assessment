# SECTION 7 : PERFORMANCE REPORT GENERATOR (aggregation / composition)
# =============================================================================
class PerformanceReportGenerator:
    def __init__(self, job: ImageJob, pipeline_result: dict, cache_result: dict, io_result: dict):
        self.job = job
        self.pipeline_result = pipeline_result
        self.cache_result = cache_result
        self.io_result = io_result

    def _identify_bottleneck(self) -> str:
        scores = {}
        # Higher CPI (relative to ideal 1.0) => pipeline stress
        scores["Pipeline (hazards/stalls)"] = self.pipeline_result["cpi"] - 1.0
        # Higher AMAT => cache stress (normalized against L1 latency baseline of 1)
        scores["Cache (memory hierarchy)"] = self.cache_result["average_memory_access_time_cycles"] / 10
        # Higher CPU utilization on the *faster* I/O method still stresses CPU
        io = self.io_result
        io_stress = min(io["interrupt_driven"]["cpu_utilization_percent"],
                         io["dma"]["cpu_utilization_percent"]) / 100
        scores["I/O (data transfer)"] = io_stress
        return max(scores, key=scores.get)

    def build(self) -> Dict:
        bottleneck = self._identify_bottleneck()
        return {
            "job_id": self.job.job_id,
            "generated_on": datetime.now().isoformat(timespec="seconds"),
            "num_images": self.job.num_images,
            "image_size_kb": self.job.image_size_kb,
            "pipeline": self.pipeline_result,
            "cache": self.cache_result,
            "io": self.io_result,
            "major_bottleneck": bottleneck,
        }

    def print_report(self, report: Dict) -> None:
        print("=" * 78)
        print(f" AI WORKLOAD PERFORMANCE REPORT  |  Job: {report['job_id']}")
        print("=" * 78)
        print(f"Images processed        : {report['num_images']}")
        print(f"Image size (KB)          : {report['image_size_kb']}")
        print("-" * 78)
        p = report["pipeline"]
        print("[1] PIPELINE ANALYSIS")
        print(f"    Instructions          : {p['instructions']}")
        print(f"    Data hazards (RAW)    : {len(p['data_hazards'])} -> {p['data_hazards']}")
        print(f"    Control hazards       : {len(p['control_hazards'])} -> {p['control_hazards']}")
        print(f"    Structural hazards    : {len(p['structural_hazards'])} -> {p['structural_hazards']}")
        print(f"    Stall/Flush cycles    : {p['stall_cycles']} / {p['flush_cycles']} "
              f"(+{p['structural_stall_cycles']} structural)")
        print(f"    Total cycles          : {p['total_cycles']}")
        print(f"    CPI                   : {p['cpi']}")
        print(f"    Execution time (ns)   : {p['execution_time_ns']}")
        print(f"    Speed-up vs unpipelined: {p['speedup']}x")
        print("-" * 78)
        c = report["cache"]
        print("[2] CACHE ANALYSIS")
        for lvl, stats in c["levels"].items():
            print(f"    {lvl:4s} -> accesses={stats['accesses']:3d} hits={stats['hits']:3d} "
                  f"misses={stats['misses']:3d} hit-ratio={stats['hit_ratio']}")
        print(f"    Main memory accesses  : {c['main_memory_accesses']}")
        print(f"    Avg memory access time: {c['average_memory_access_time_cycles']} cycles")
        print("-" * 78)
        io = report["io"]
        print("[3] I/O & DMA ANALYSIS")
        print(f"    Interrupt-driven      : {io['interrupt_driven']}")
        print(f"    DMA                   : {io['dma']}")
        print(f"    More efficient method : {io['more_efficient_method']}")
        print("-" * 78)
        print(f"MAJOR PERFORMANCE BOTTLENECK : {report['major_bottleneck']}")
        print("=" * 78)


