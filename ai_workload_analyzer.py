class WorkloadAnalyzerError(Exception):
    """Base exception for every error raised inside this application."""


class InvalidJobFileError(WorkloadAnalyzerError):
    """Raised when the input workload file is missing / malformed."""


class InvalidInstructionError(WorkloadAnalyzerError):
    """Raised when an instruction record does not have the required fields."""


class CacheConfigurationError(WorkloadAnalyzerError):
    """Raised when a cache level is configured with invalid parameters."""


class IOConfigurationError(WorkloadAnalyzerError):
    """Raised when I/O / DMA parameters are invalid (e.g. zero transfer rate)."""


