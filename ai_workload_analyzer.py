# SECTION 5 : HIERARCHICAL CACHE SIMULATOR (L1 -> L2 -> L3 -> Main Memory)
# =============================================================================
class CacheLevel:
    """A single direct-mapped cache level."""

    def __init__(self, name: str, size_kb: int, block_size_b: int, latency_cycles: int):
        if size_kb <= 0 or block_size_b <= 0 or latency_cycles < 0:
            raise CacheConfigurationError(f"Invalid configuration for cache level {name}")
        self.name = name
        self.size_bytes = size_kb * 1024
        self.block_size_b = block_size_b
        self.num_lines = max(1, self.size_bytes // self.block_size_b)
        self.latency_cycles = latency_cycles
        self.lines: Dict[int, int] = {}   # line_index -> tag
        self.hits = 0
        self.misses = 0

    def access(self, address: int) -> bool:
        block_no = address // self.block_size_b
        line_index = block_no % self.num_lines
        tag = block_no // self.num_lines
        if self.lines.get(line_index) == tag:
            self.hits += 1
            return True
        self.lines[line_index] = tag
        self.misses += 1
        return False

    @property
    def accesses(self) -> int:
        return self.hits + self.misses

    @property
    def hit_ratio(self) -> float:
        return round(self.hits / self.accesses, 4) if self.accesses else 0.0


class CacheAnalyzer(BaseAnalyzer):
    def __init__(self, addresses: List[int], cache_cfg: List[dict], main_mem_latency: int = 100):
        super().__init__("Hierarchical Cache Analyzer")
        self.addresses = addresses
        self.levels = [
            CacheLevel(c["name"], c["size_kb"], c["block_size_b"], c["latency_cycles"])
            for c in cache_cfg
        ]
        self.main_mem_latency = main_mem_latency
        self.result: Dict = {}

    def run(self) -> Dict:
        main_mem_accesses = 0
        total_latency = 0

        for addr in self.addresses:
            for level in self.levels:
                hit = level.access(addr)
                total_latency += level.latency_cycles
                if hit:
                    break
            else:
                main_mem_accesses += 1
                total_latency += self.main_mem_latency

        total_accesses = len(self.addresses) if self.addresses else 1
        amat = round(total_latency / total_accesses, 3)

        per_level = {}
        for level in self.levels:
            per_level[level.name] = {
                "accesses": level.accesses,
                "hits": level.hits,
                "misses": level.misses,
                "hit_ratio": level.hit_ratio,
                "miss_ratio": round(1 - level.hit_ratio, 4) if level.accesses else 0.0,
            }

        self.result = {
            "total_memory_accesses": len(self.addresses),
            "main_memory_accesses": main_mem_accesses,
            "average_memory_access_time_cycles": amat,
            "levels": per_level,
        }
        return self.result

    def summary(self) -> str:
        r = self.result
        l1 = r["levels"].get("L1", {})
        return (f"Cache: {r['total_memory_accesses']} accesses | "
                f"L1 hit-ratio={l1.get('hit_ratio', 0)} | AMAT={r['average_memory_access_time_cycles']} cycles")


