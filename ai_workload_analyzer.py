# SECTION 3 : ABSTRACT BASE FOR ALL ANALYZERS  (demonstrates inheritance)
# =============================================================================
class BaseAnalyzer(ABC):
    """Common contract shared by Pipeline, Cache and I/O analyzers."""

    def __init__(self, name: str):
        self.name = name

    @abstractmethod
    def run(self):
        """Execute the analysis and return a result dict."""
        raise NotImplementedError

    @abstractmethod
    def summary(self) -> str:
        """Return a short, human-readable summary line (polymorphism)."""
        raise NotImplementedError


# =============================================================================
# SECTION 4 : FIVE-STAGE PIPELINE SIMULATOR
# =============================================================================
class PipelineSimulator(BaseAnalyzer):
    STAGES = ("IF", "ID", "EX", "MEM", "WB")

    def __init__(self, instructions: List[Instruction], clock_period_ns: float = 1.0):
        super().__init__("Pipeline Hazard Analyzer")
        self.instructions = instructions
        self.clock_period_ns = clock_period_ns
        self.result: Dict = {}

    # ---- hazard detection -------------------------------------------------
    def _detect_data_hazards(self) -> List[Tuple[str, str]]:
        """RAW hazard: instruction i's source register was written by one of
        the previous two instructions still in the pipeline (classic 5-stage
        forwarding window)."""
        hazards = []
        for idx, inst in enumerate(self.instructions):
            window = self.instructions[max(0, idx - 2):idx]
            for prev in window:
                if prev.dest_reg and prev.dest_reg in inst.src_regs:
                    hazards.append((prev.inst_id, inst.inst_id))
        return hazards

    def _detect_control_hazards(self) -> List[str]:
        return [inst.inst_id for inst in self.instructions if inst.is_branch()]

    def _detect_structural_hazards(self) -> List[Tuple[str, str]]:
        """Two consecutive MEM-stage instructions (LOAD/STORE) contending for
        the single memory port is treated as a structural hazard."""
        hazards = []
        for idx in range(1, len(self.instructions)):
            cur, prev = self.instructions[idx], self.instructions[idx - 1]
            if cur.is_memory_op() and prev.is_memory_op():
                hazards.append((prev.inst_id, cur.inst_id))
        return hazards

    # ---- main run -----------------------------------------------------------
    def run(self) -> Dict:
        n = len(self.instructions)
        data_hazards = self._detect_data_hazards()
        control_hazards = self._detect_control_hazards()
        structural_hazards = self._detect_structural_hazards()

        stall_cycles = len(data_hazards) * 1          # 1-cycle forwarding stall
        flush_cycles = len(control_hazards) * 2        # 2-cycle branch flush
        structural_stalls = len(structural_hazards) * 1

        ideal_cycles = n + len(self.STAGES) - 1         # no-hazard pipeline fill
        total_cycles = ideal_cycles + stall_cycles + flush_cycles + structural_stalls

        cpi = round(total_cycles / n, 3) if n else 0
        execution_time_ns = round(total_cycles * self.clock_period_ns, 3)
        non_pipelined_cycles = n * len(self.STAGES)
        speedup = round(non_pipelined_cycles / total_cycles, 3) if total_cycles else 0

        self.result = {
            "instructions": n,
            "data_hazards": data_hazards,
            "control_hazards": control_hazards,
            "structural_hazards": structural_hazards,
            "stall_cycles": stall_cycles,
            "flush_cycles": flush_cycles,
            "structural_stall_cycles": structural_stalls,
            "total_cycles": total_cycles,
            "cpi": cpi,
            "execution_time_ns": execution_time_ns,
            "non_pipelined_cycles": non_pipelined_cycles,
            "speedup": speedup,
        }
        return self.result

    def summary(self) -> str:
        r = self.result
        return (f"Pipeline: {r['instructions']} instr | CPI={r['cpi']} | "
                f"cycles={r['total_cycles']} | speed-up={r['speedup']}x")


