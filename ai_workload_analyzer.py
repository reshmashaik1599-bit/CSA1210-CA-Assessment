# SECTION 2 : DOMAIN MODEL  (Instruction / Job)
# =============================================================================
@dataclass
class Instruction:
    """Represents one processor instruction issued while processing an image."""
    inst_id: str
    operation: str                 # LOAD, STORE, ADD, SUB, MUL, BRANCH, NOP ...
    src_regs: List[str] = field(default_factory=list)
    dest_reg: Optional[str] = None
    mem_address: Optional[int] = None

    def __post_init__(self):
        if not self.inst_id or not self.operation:
            raise InvalidInstructionError(
                f"Instruction is missing an id/operation: {self}"
            )
        self.operation = self.operation.upper()

    def is_memory_op(self) -> bool:
        return self.operation in ("LOAD", "STORE")

    def is_branch(self) -> bool:
        return self.operation == "BRANCH"

    def __str__(self) -> str:
        return (f"{self.inst_id}:{self.operation} "
                f"src={self.src_regs} dst={self.dest_reg} mem={self.mem_address}")


@dataclass
class ImageJob:
    """Represents one image-processing job submitted to the AI data center."""
    job_id: str
    num_images: int
    image_size_kb: float
    instructions: List[Instruction]

    @classmethod
    def from_dict(cls, data: dict) -> "ImageJob":
        try:
            instructions = [
                Instruction(
                    inst_id=i["inst_id"],
                    operation=i["operation"],
                    src_regs=i.get("src_regs", []),
                    dest_reg=i.get("dest_reg"),
                    mem_address=i.get("mem_address"),
                )
                for i in data["instructions"]
            ]
            return cls(
                job_id=data["job_id"],
                num_images=int(data["num_images"]),
                image_size_kb=float(data["image_size_kb"]),
                instructions=instructions,
            )
        except KeyError as exc:
            raise InvalidJobFileError(f"Missing required field: {exc}") from exc


